(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) root.CaptionGrabExtractor = api;
})(typeof globalThis === 'undefined' ? this : globalThis, function () {
  'use strict';

  const REQUEST_ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
  const VIDEO_ID = /^[A-Za-z0-9_-]{11}$/;

  function parseTimestamp(value) {
    if (typeof value !== 'string') return null;
    const parts = value.trim().split(':');
    if ((parts.length !== 2 && parts.length !== 3) || parts.some(part => !/^\d+$/.test(part))) return null;
    const values = parts.map(Number);
    const seconds = values.at(-1);
    const minutes = values.at(-2);
    if (seconds > 59 || (parts.length === 3 && (minutes > 59 || values[0] > 999))) return null;
    const totalSeconds = parts.length === 3
      ? values[0] * 3600 + values[1] * 60 + seconds
      : values[0] * 60 + seconds;
    return totalSeconds * 1000;
  }

  function extractCues(segments) {
    if (!segments || typeof segments[Symbol.iterator] !== 'function') return [];
    const cues = [];
    for (const segment of segments) {
      if (!segment || typeof segment.querySelector !== 'function') continue;
      const timestampNode = segment.querySelector('.segment-timestamp, .timestamp');
      const textNode = segment.querySelector('.segment-text, yt-formatted-string.segment-text');
      const startTimeMilliseconds = parseTimestamp(timestampNode?.innerText ?? timestampNode?.textContent ?? '');
      const rawText = textNode?.innerText ?? textNode?.textContent ?? '';
      const text = String(rawText).replace(/\r\n?/g, '\n').trim();
      if (startTimeMilliseconds === null || !text) continue;
      cues.push({ startTimeMilliseconds, text });
    }
    return cues;
  }

  function choosePreferredEnglishLanguage(availableLanguages) {
    const normalized = [];
    const seen = new Set();
    for (const value of Array.isArray(availableLanguages) ? availableLanguages : []) {
      const label = String(value ?? '').replace(/\s+/g, ' ').trim();
      const key = label.toLocaleLowerCase();
      if (!label || seen.has(key)) continue;
      seen.add(key);
      normalized.push(label);
    }
    const hasRegularEnglish = normalized.some(value => /^English$/i.test(value));
    const hasGeneratedEnglish = normalized.some(value => /^English\s+\(auto-generated\)$/i.test(value));
    const selectedLanguage = hasRegularEnglish ? 'English' : hasGeneratedEnglish ? 'English (auto-generated)' : null;
    return {
      availableLanguages: normalized,
      selectedLanguage,
      isAutoGenerated: selectedLanguage === null ? null : selectedLanguage === 'English (auto-generated)'
    };
  }

  function normalizedEnglishLanguage(value) {
    const label = String(value ?? '').replace(/\s+/g, ' ').trim();
    if (/^English$/i.test(label)) return 'English';
    if (/^English\s+\(auto-generated\)$/i.test(label)) return 'English (auto-generated)';
    return null;
  }

  function domElements(root) {
    const elements = [];
    const pending = [root];
    const seen = new Set();
    while (pending.length) {
      const current = pending.pop();
      if (!current || seen.has(current)) continue;
      seen.add(current);
      elements.push(current);
      let descendants = [];
      try { descendants = [...(current.querySelectorAll?.('*') ?? [])]; } catch { /* ignore inaccessible roots */ }
      for (const node of descendants) {
        if (seen.has(node)) continue;
        seen.add(node);
        elements.push(node);
        if (node.shadowRoot) pending.push(node.shadowRoot);
      }
      if (current.shadowRoot) pending.push(current.shadowRoot);
    }
    return elements;
  }

  function matchesDOM(node, selector) {
    try { return Boolean(node?.matches?.(selector)); } catch { return false; }
  }

  function isVisibleDOM(node, document) {
    let current = node;
    const seen = new Set();
    while (current && !seen.has(current)) {
      seen.add(current);
      if (current.hidden || current.getAttribute?.('aria-hidden') === 'true' || current.isConnected === false) return false;
      if (current.style?.display === 'none' || current.style?.visibility === 'hidden') return false;
      try {
        const style = document?.defaultView?.getComputedStyle?.(current);
        if (style && (style.display === 'none' || style.visibility === 'hidden' || Number(style.opacity || 1) <= 0)) return false;
      } catch { /* computed style is optional in fixtures */ }
      current = current.parentElement ?? current.getRootNode?.()?.host ?? null;
    }
    return true;
  }

  function nodeText(node) {
    return String(node?.innerText ?? node?.textContent ?? '').replace(/\s+/g, ' ').trim();
  }

  function languageMenuTrigger(panel, document) {
    const elements = domElements(panel);
    const isControl = node => matchesDOM(node, 'button, [role="button"], tp-yt-paper-button') && isVisibleDOM(node, document);
    const named = elements.filter(node =>
      /^(?:language-menu|dropdown-trigger)$/i.test(String(node.id ?? '')) ||
      /language/i.test(`${node.getAttribute?.('aria-label') ?? ''} ${node.getAttribute?.('title') ?? ''}`)
    );
    for (const node of named) {
      if (isControl(node)) return node;
      const nested = domElements(node).find(child => child !== node && isControl(child));
      if (nested) return nested;
      if (typeof node.click === 'function') return node;
    }
    return elements.find(node => isControl(node) && [
      node.getAttribute?.('aria-label'), node.getAttribute?.('title'), nodeText(node)
    ].some(value => normalizedEnglishLanguage(value) !== null)) ?? null;
  }

  function currentTranscriptLanguage(panel) {
    const elements = domElements(panel);
    const trigger = elements.find(node => /^(?:language-menu|dropdown-trigger)$/i.test(String(node.id ?? '')));
    const controlCandidates = [trigger, ...elements.filter(node =>
      /language/i.test(`${node.getAttribute?.('aria-label') ?? ''} ${node.getAttribute?.('title') ?? ''}`)
    )].filter(Boolean);
    for (const node of controlCandidates) {
      for (const value of [node.getAttribute?.('aria-label'), node.getAttribute?.('title'), nodeText(node)]) {
        const language = normalizedEnglishLanguage(value);
        if (language) return language;
      }
    }
    const selectedOption = elements.find(node =>
      matchesDOM(node, '[role="option"], [role="menuitem"], tp-yt-paper-item') &&
      (node.getAttribute?.('aria-selected') === 'true' || node.getAttribute?.('selected') !== null ||
        /(?:^|\s)(?:selected|iron-selected)(?:\s|$)/i.test(String(node.className ?? '')))
    );
    if (selectedOption) {
      const language = normalizedEnglishLanguage(nodeText(selectedOption));
      if (language) return language;
    }
    const lines = String(panel?.innerText ?? '').split(/\n+/).map(line => line.trim()).filter(Boolean);
    return [...lines].reverse().map(normalizedEnglishLanguage).find(Boolean) ?? null;
  }

  function visibleMenuRoots(document) {
    const menuSelector = '[role="listbox"], [role="menu"], tp-yt-paper-listbox, tp-yt-paper-menu, tp-yt-iron-dropdown, ytd-menu-popup-renderer';
    return domElements(document).filter(node =>
      (matchesDOM(node, menuSelector) || String(node.id ?? '') === 'items') && isVisibleDOM(node, document)
    );
  }

  function controlledMenuIDs(trigger) {
    return new Set(['aria-controls', 'aria-owns']
      .flatMap(name => String(trigger?.getAttribute?.(name) ?? '').split(/\s+/))
      .filter(Boolean));
  }

  function visibleLanguageOptions(panel, document, { trigger = null, baselineMenuRoots = null } = {}) {
    const optionSelector = '[role="option"], [role="menuitem"], tp-yt-paper-item, ytd-menu-service-item-renderer';
    const panelElements = new Set(domElements(panel));
    const linkedMenuIDs = controlledMenuIDs(trigger);
    const menuRoots = visibleMenuRoots(document).filter(node =>
      panelElements.has(node) ||
      (node.id && linkedMenuIDs.has(node.id)) ||
      (baselineMenuRoots && !baselineMenuRoots.has(node))
    );
    const roots = menuRoots.length ? menuRoots : [panel];
    let fallbackRecords = [];
    for (const root of roots) {
      const records = domElements(root)
        .filter(node => matchesDOM(node, optionSelector) && isVisibleDOM(node, document))
        .map(node => ({ node, label: nodeText(node) }))
        .filter(record => record.label);
      if (records.some(record => normalizedEnglishLanguage(record.label))) return records;
      if (!fallbackRecords.length && records.length) fallbackRecords = records;
    }
    return fallbackRecords;
  }

  function transcriptCueSnapshot(panel) {
    const selector = 'ytd-transcript-segment-renderer, yt-transcript-segment-renderer, .transcript-segment';
    const rows = domElements(panel).filter(node => matchesDOM(node, selector) && isVisibleDOM(node, panel?.ownerDocument));
    return { rows, signature: JSON.stringify(rows.map(node => nodeText(node))) };
  }

  function transcriptSnapshotChanged(before, after) {
    return before.signature !== after.signature || before.rows.length !== after.rows.length;
  }

  async function selectPreferredEnglishTranscript({
    panel,
    document = globalThis.document,
    sleep = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds)),
    now = () => Date.now(),
    timeoutMs = 10_000,
    pollIntervalMs = 150
  } = {}) {
    const currentlySelectedLanguage = currentTranscriptLanguage(panel);
    const trigger = panel ? languageMenuTrigger(panel, document) : null;
    const failure = (reason, availableLanguages = [], selectedLanguage = null, menuInspected = false) => ({
      ok: false, reason, availableLanguages, currentlySelectedLanguage,
      selectedLanguage, isAutoGenerated: selectedLanguage ? /auto-generated/i.test(selectedLanguage) : null,
      selectionConfirmed: false, transcriptRefreshed: false, menuInspected
    });
    if (!panel || !document) return failure('transcript-panel-unavailable');
    if (!trigger) {
      return failure('language-menu-unavailable');
    }

    let records = visibleLanguageOptions(panel, document, { trigger });
    if (!records.length) {
      const baselineMenuRoots = new Set(visibleMenuRoots(document));
      try { trigger.click(); } catch { return failure('language-menu-click-failed'); }
      const deadline = now() + timeoutMs;
      while (now() < deadline && !records.length) {
        await sleep(Math.min(pollIntervalMs, Math.max(1, deadline - now())));
        records = visibleLanguageOptions(panel, document, { trigger, baselineMenuRoots });
      }
    }

    const availableLanguages = [...new Set(records.map(record => record.label))];
    if (!records.length) {
      return failure('language-options-unavailable', availableLanguages);
    }

    const choice = choosePreferredEnglishLanguage(availableLanguages);
    if (!choice.selectedLanguage) return failure('no-english-language', choice.availableLanguages, null, true);
    const selectedRecord = records.find(record => normalizedEnglishLanguage(record.label) === choice.selectedLanguage);
    if (!selectedRecord) return failure('english-option-not-clickable', choice.availableLanguages, choice.selectedLanguage, true);

    const before = transcriptCueSnapshot(panel);
    try { selectedRecord.node.click(); } catch {
      return failure('english-option-click-failed', choice.availableLanguages, choice.selectedLanguage, true);
    }

    const selectionDeadline = now() + timeoutMs;
    let confirmedLanguage = currentTranscriptLanguage(panel);
    while (confirmedLanguage !== choice.selectedLanguage && now() < selectionDeadline) {
      await sleep(Math.min(pollIntervalMs, Math.max(1, selectionDeadline - now())));
      confirmedLanguage = currentTranscriptLanguage(panel);
    }
    if (confirmedLanguage !== choice.selectedLanguage) {
      return failure('language-selection-not-confirmed', choice.availableLanguages, choice.selectedLanguage, true);
    }

    const selectionChanged = currentlySelectedLanguage !== choice.selectedLanguage;
    if (!selectionChanged) {
      return {
        ok: true, reason: null, availableLanguages: choice.availableLanguages, currentlySelectedLanguage,
        selectedLanguage: choice.selectedLanguage, isAutoGenerated: choice.isAutoGenerated,
        selectionConfirmed: true, transcriptRefreshed: true, menuInspected: true
      };
    }

    const refreshDeadline = now() + timeoutMs;
    const unchangedFallbackMs = Math.min(3_000, timeoutMs);
    let lastSignature = null;
    let stableChecks = 0;
    let transcriptRefreshed = false;
    while (now() < refreshDeadline) {
      const current = transcriptCueSnapshot(panel);
      if (transcriptSnapshotChanged(before, current)) {
        transcriptRefreshed = current.rows.length > 0;
        if (current.signature === lastSignature) stableChecks += 1;
        else stableChecks = 0;
        lastSignature = current.signature;
        if (transcriptRefreshed && stableChecks >= 1) break;
      } else if (current.rows.length && now() - (refreshDeadline - timeoutMs) >= unchangedFallbackMs) {
        transcriptRefreshed = false;
        break;
      }
      await sleep(Math.min(pollIntervalMs, Math.max(1, refreshDeadline - now())));
    }
    if (!transcriptRefreshed) {
      return failure('transcript-refresh-not-confirmed', choice.availableLanguages, choice.selectedLanguage, true);
    }
    return {
      ok: true, reason: null, availableLanguages: choice.availableLanguages, currentlySelectedLanguage,
      selectedLanguage: choice.selectedLanguage, isAutoGenerated: choice.isAutoGenerated,
      selectionConfirmed: true, transcriptRefreshed: true, menuInspected: true
    };
  }

  function buildCaptureMessage(details, cues) {
    if (!details || !REQUEST_ID.test(details.requestID ?? '')) throw new Error('Invalid CaptionGrab request.');
    if (!VIDEO_ID.test(details.videoID ?? '')) throw new Error('Invalid YouTube video ID.');
    const label = String(details.languageName ?? '').trim();
    if (!/^English(?:\s+\(auto-generated\))?$/i.test(label)) {
      throw new Error('The transcript shown in Chrome is not English. Select the English transcript and try again.');
    }
    if (!Array.isArray(cues) || cues.length === 0) throw new Error('YouTube did not show any transcript captions.');
    const title = String(details.title ?? '').trim();
    if (!title || title.length > 500) throw new Error('Could not read the video title from YouTube.');
    const normalizedCues = cues.map(cue => ({
      startTimeMilliseconds: Number(cue.startTimeMilliseconds),
      text: String(cue.text ?? '')
    }));
    if (normalizedCues.some(cue => !Number.isSafeInteger(cue.startTimeMilliseconds) || cue.startTimeMilliseconds < 0 || !cue.text.trim())) {
      throw new Error('The transcript contains an invalid caption segment.');
    }
    return {
      type: 'captiongrab.transcript',
      requestID: details.requestID,
      videoID: details.videoID,
      videoURL: `https://www.youtube.com/watch?v=${details.videoID}`,
      title,
      captionLanguage: 'English',
      isAutoGenerated: /auto-generated/i.test(label) ? true : (details.isAutoGenerated === false ? false : null),
      cues: normalizedCues
    };
  }

  return {
    parseTimestamp,
    extractCues,
    choosePreferredEnglishLanguage,
    selectPreferredEnglishTranscript,
    buildCaptureMessage
  };
});
