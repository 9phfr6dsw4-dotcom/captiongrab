(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) root.CaptionGrabExtractor = api;
})(typeof globalThis === 'undefined' ? this : globalThis, function () {
  'use strict';

  const REQUEST_ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
  const VIDEO_ID = /^[A-Za-z0-9_-]{11}$/;

  function parseTimestamp(value) {
    if (typeof value !== 'string') return null;
    const parts = value.trim().split(':');
    if ((parts.length !== 2 && parts.length !== 3) || parts.some(part => !/^\d+$/.test(part))) return null;
    const values = parts.map(Number);
    const seconds = values.at(-1);
    const minutes = values.at(-2);
    if (seconds > 59 || (parts.length === 3 && (minutes > 59 || values[0] > 999))) return null;
    const totalSeconds = parts.length === 3
      ? values[0] * 3600 + values[1] * 60 + seconds
      : values[0] * 60 + seconds;
    return totalSeconds * 1000;
  }

  function extractCues(segments) {
    if (!segments || typeof segments[Symbol.iterator] !== 'function') return [];
    const cues = [];
    for (const segment of segments) {
      if (!segment || typeof segment.querySelector !== 'function') continue;
      const timestampNode = segment.querySelector('.segment-timestamp, .timestamp');
      const textNode = segment.querySelector('.segment-text, yt-formatted-string.segment-text');
      const startTimeMilliseconds = parseTimestamp(timestampNode?.innerText ?? timestampNode?.textContent ?? '');
      const rawText = textNode?.innerText ?? textNode?.textContent ?? '';
      const text = String(rawText).replace(/\r\n?/g, '\n').trim();
      if (startTimeMilliseconds === null || !text) continue;
      cues.push({ startTimeMilliseconds, text });
    }
    return cues;
  }

  function buildCaptureMessage(details, cues) {
    if (!details || !REQUEST_ID.test(details.requestID ?? '')) throw new Error('Invalid CaptionGrab request.');
    if (!VIDEO_ID.test(details.videoID ?? '')) throw new Error('Invalid YouTube video ID.');
    const label = String(details.languageName ?? '').trim();
    if (!/^English(?:\s+\(auto-generated\))?$/i.test(label)) {
      throw new Error('The transcript shown in Chrome is not English. Select the English transcript and try again.');
    }
    if (!Array.isArray(cues) || cues.length === 0) throw new Error('YouTube did not show any transcript captions.');
    const title = String(details.title ?? '').trim();
    if (!title || title.length > 500) throw new Error('Could not read the video title from YouTube.');
    const normalizedCues = cues.map(cue => ({
      startTimeMilliseconds: Number(cue.startTimeMilliseconds),
      text: String(cue.text ?? '')
    }));
    if (normalizedCues.some(cue => !Number.isSafeInteger(cue.startTimeMilliseconds) || cue.startTimeMilliseconds < 0 || !cue.text.trim())) {
      throw new Error('The transcript contains an invalid caption segment.');
    }
    return {
      type: 'captiongrab.transcript',
      requestID: details.requestID,
      videoID: details.videoID,
      videoURL: `https://www.youtube.com/watch?v=${details.videoID}`,
      title,
      captionLanguage: 'English',
      isAutoGenerated: /auto-generated/i.test(label) ? true : (details.isAutoGenerated === false ? false : null),
      cues: normalizedCues
    };
  }

  return { parseTimestamp, extractCues, buildCaptureMessage };
});
