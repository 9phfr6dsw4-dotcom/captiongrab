import Foundation

public enum ChromeTranscriptMessageError: Error, Equatable, LocalizedError, Sendable {
    case transcriptUnavailable(String)
    case invalidMessage(String)

    public var errorDescription: String? {
        switch self {
        case .transcriptUnavailable(let message): message
        case .invalidMessage(let message): message
        }
    }
}

public struct ChromeTranscriptProgress: Codable, Equatable, Sendable {
    public let descriptionExpanded: Bool
    public let transcriptSectionFound: Bool
    public let transcriptButtonFound: Bool
    public let transcriptButtonClicked: Bool
    public let panelOpened: Bool
    public let transcriptTabSelected: Bool
    public let transcriptLinesLoaded: Bool

    public var summary: String {
        let state: (Bool) -> String = { $0 ? "yes" : "no" }
        return [
            "Chrome automation progress:",
            "- Description expanded: \(state(descriptionExpanded))",
            "- Transcript section found: \(state(transcriptSectionFound))",
            "- Show transcript button found: \(state(transcriptButtonFound))",
            "- Show transcript button clicked: \(state(transcriptButtonClicked))",
            "- Transcript panel opened: \(state(panelOpened))",
            "- Transcript tab selected: \(state(transcriptTabSelected))",
            "- Transcript lines loaded: \(state(transcriptLinesLoaded))"
        ].joined(separator: "\n")
    }
}

public struct ChromeTranscriptMessage: Codable, Equatable, Sendable {
    public let type: String
    public let requestID: String
    public let videoID: String
    public let videoURL: String?
    public let title: String?
    public let captionLanguage: String?
    public let isAutoGenerated: Bool?
    public let cues: [TranscriptCue]?
    public let error: String?
    public let progress: ChromeTranscriptProgress?
    public let debugLog: String?

    public func makeTranscript(
        expectedRequestID: String,
        expectedVideoID: String,
        canonicalURL: URL
    ) throws -> TranscriptData {
        guard (debugLog?.count ?? 0) <= 30_000 else {
            throw ChromeTranscriptMessageError.invalidMessage("Chrome returned an oversized diagnostic log.")
        }
        guard let requestUUID = UUID(uuidString: requestID),
              let expectedUUID = UUID(uuidString: expectedRequestID),
              requestUUID == expectedUUID,
              isValidVideoID(videoID),
              videoID == expectedVideoID,
              isValidWatchURL(canonicalURL.absoluteString, matching: videoID)
        else {
            throw ChromeTranscriptMessageError.invalidMessage("The Chrome response did not match the video requested in CaptionGrab.")
        }

        if type == "captiongrab.error" {
            let message = String((error ?? "Chrome could not read the transcript.").prefix(1_000))
            let detail = progress.map { "\n\n\($0.summary)" } ?? ""
            throw ChromeTranscriptMessageError.transcriptUnavailable(message + detail)
        }
        guard type == "captiongrab.transcript",
              isValidWatchURL(videoURL, matching: videoID) else {
            throw ChromeTranscriptMessageError.invalidMessage("Chrome returned an unsupported or mismatched response.")
        }
        guard let language = captionLanguage?.trimmingCharacters(in: .whitespacesAndNewlines).lowercased(),
              language == "english" || language == "en" else {
            throw ChromeTranscriptMessageError.invalidMessage("Chrome did not confirm that the transcript is English.")
        }
        guard let title = title?.trimmingCharacters(in: .whitespacesAndNewlines),
              !title.isEmpty, title.count <= 500,
              let cues, !cues.isEmpty, cues.count <= 100_000 else {
            throw ChromeTranscriptMessageError.invalidMessage("Chrome returned an empty or invalid transcript.")
        }
        let totalCaptionCharacters = cues.reduce(0) { partial, cue in
            partial.addingReportingOverflow(cue.text.utf8.count).overflow ? Int.max : partial + cue.text.utf8.count
        }
        guard totalCaptionCharacters <= 10_000_000,
              cues.allSatisfy({ $0.startTimeMilliseconds >= 0 && !$0.text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty }) else {
            throw ChromeTranscriptMessageError.invalidMessage("Chrome returned invalid caption segments.")
        }

        return TranscriptData(
            videoTitle: title,
            videoURL: canonicalURL,
            isAutoGenerated: isAutoGenerated,
            cues: cues
        )
    }

    private func isValidVideoID(_ value: String) -> Bool {
        value.count == 11 && value.unicodeScalars.allSatisfy {
            CharacterSet(charactersIn: "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-").contains($0)
        }
    }

    private func isValidWatchURL(_ value: String?, matching videoID: String) -> Bool {
        guard let value, let components = URLComponents(string: value),
              components.scheme?.lowercased() == "https",
              components.host?.lowercased() == "www.youtube.com",
              components.path == "/watch",
              components.queryItems?.first(where: { $0.name == "v" })?.value == videoID,
              components.user == nil, components.password == nil, components.port == nil else { return false }
        return true
    }
}
